// Builds a consumer contract barrel from private compiler output.
import { existsSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

export function writeIndex(dir) {
  const names = readdirSync(dir)
    .filter((f) => f.endsWith('.ts') && f !== 'index.ts')
    .map((f) => f.slice(0, -3))
    .sort();
  const header = '// Generated by tooling/codegen/gen-protocol-index.mjs. Do not edit.\n';
  const catalog = existsSync(join(dir, 'domain-catalog.json'))
    ? 'export { default as domainCatalog } from "./domain-catalog.json";\n'
    : '';
  writeFileSync(
    join(dir, 'index.ts'),
    header +
      names
        .flatMap((name) =>
          // Runtime exports remain explicit; type exports need no filename convention.
          name === 'rpc-methods'
            ? [
                'export type { MethodMap } from "./rpc-methods";',
                'export { METHODS } from "./rpc-methods";'
              ]
            : [`export type * from "./${name}";`]
        )
        .join('\n') +
      '\n' +
      catalog
  );
}
