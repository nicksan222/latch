    #[test]
    fn all_kinds_redact_reveal_and_preserve_absent_secrets() {
        for (body, paths) in strategy_fixtures() {
            let redacted = payload(&body, false);
            let revealed = payload(&body, true);
            let redacted_json = serde_json::to_value(&redacted).unwrap();
            let revealed_json = serde_json::to_value(&revealed).unwrap();
            assert_eq!(
                secret_paths(&body),
                paths
                    .iter()
                    .map(|(p, _, _)| p.to_string())
                    .collect::<Vec<_>>()
            );
            for (path, pointer, _) in paths {
                assert!(redacted_json.pointer(pointer).unwrap().is_null());
                assert_eq!(
                    revealed_json.pointer(pointer).unwrap().as_str().unwrap(),
                    reveal_field(&body, path).unwrap().as_str()
                );
            }
            assert_eq!(body_from_payload(&redacted, Some(&body)).unwrap(), body);
            assert_eq!(body_from_payload(&revealed, None).unwrap(), body);
        }
    }

