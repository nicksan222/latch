/// Shared null/empty semantics, usable for both masked wire drafts and stored
/// documents. Required document fields materialize absent values as empty.
pub(crate) fn merge_secret<'a>(
    input: Option<&'a str>,
    stored: Option<&'a str>,
    optional: bool,
) -> Option<&'a str> {
    match input {
        Some("") if optional => None,
        Some(value) => Some(value),
        None => stored,
    }
}
fn keep(input: &Option<String>, stored: Option<&String>) -> String {
    merge_secret(input.as_deref(), stored.map(String::as_str), false)
        .unwrap_or_default()
        .to_owned()
}

/// Optional secret: `None` keeps the stored value, `Some("")` clears it.
fn keep_opt(input: &Option<String>, stored: Option<&Option<String>>) -> Option<String> {
    merge_secret(input.as_deref(), stored.and_then(|s| s.as_deref()), true).map(str::to_owned)
}

fn unique_keys<'a>(keys: impl Iterator<Item = &'a str>, what: &str) -> Result<()> {
    let mut seen = std::collections::HashSet::new();
    for k in keys {
        if k.is_empty() {
            return Err(Error::invalid(format!("{what} key must not be empty")));
        }
        if !seen.insert(k) {
            return Err(Error::invalid(format!("duplicate {what} key `{k}`")));
        }
    }
    Ok(())
}

type DigestStrategy = fn(&EntryBody, &mut dyn FnMut(&str, [u8; 32])) -> Result<()>;

/// A registered secret kind. Typed adapters are generated by `secret_kind!`;
/// document and wire enums remain the compatibility boundary.
pub struct SecretKind {
    /// Presentation metadata owned by each secret strategy.
    pub ui_order: u8,
    pub label: &'static str,
    pub primary_copy_field: Option<&'static str>,
    pub default_payload: fn() -> EntryPayload,
    pub diff_fields: &'static [&'static str],
    pub ui_validate: fn(&EntryPayload, &mut BTreeMap<String, String>) -> Result<()>,
    pub wire_secrets: &'static [(&'static str, bool)],
    pub entry_type: EntryType,
    pub id: &'static str,
    accepts_payload: fn(&EntryPayload) -> bool,
    merge: fn(&EntryPayload, Option<&EntryBody>) -> Result<EntryBody>,
    payload: fn(&EntryBody, bool) -> Result<EntryPayload>,
    paths: fn(&EntryBody) -> Result<Vec<String>>,
    reveal: fn(&EntryBody, &str) -> Result<Zeroizing<String>>,
    subtitle: fn(&EntryBody) -> Result<String>,
    digests: DigestStrategy,
}

inventory::collect!(SecretKind);

/// Declare the variant and its typed behavior together. Only these adapters
/// know about enum matching; each strategy implements operations on its own
/// data/document types. A mismatched stored kind deliberately means no merge.
macro_rules! secret_kind {
    (
        id: $id:literal,
        ui: ($order:literal, $label:literal, $copy:expr),
        defaults: $defaults:expr,
        wire_secrets: $wire_secrets:expr,
        variant: $variant:ident, data: $data:ty, doc: $doc:ty,
        diff_fields: $diff_fields:expr,
        validate_ui: $validate_ui:ident,
        merge: $merge:ident,
        payload: $payload:ident,
        paths: $paths:ident,
        reveal: $reveal:ident,
        subtitle: $subtitle:ident,
        digests: $digests:ident $(,)?
    ) => {
        inventory::submit! {
            SecretKind {
                ui_order: $order, label: $label, primary_copy_field: $copy,
                default_payload: || EntryPayload::$variant(serde_json::from_value($defaults).expect("valid kind defaults")),
                wire_secrets: $wire_secrets,
                diff_fields: $diff_fields,
                ui_validate: |payload, errors| {
                    let EntryPayload::$variant(data) = payload else {return Err(registry_error())};
                    $validate_ui(data, errors); Ok(())
                },
                entry_type: EntryType::$variant,
                id: $id,
                accepts_payload: |payload| matches!(payload, EntryPayload::$variant(_)),
                merge: |payload, stored| {
                    let EntryPayload::$variant(d) = payload else {
                        return Err(registry_error());
                    };
                    let d: &$data = d;
                    let s: Option<&$doc> = match stored {
                        Some(EntryBody::$variant(s)) => Some(s),
                        _ => None,
                    };
                    $merge(d, s).map(EntryBody::$variant)
                },
                payload: |body, reveal| {
                    let EntryBody::$variant(d) = body else {
                        return Err(registry_error());
                    };
                    Ok(EntryPayload::$variant($payload(d, reveal)))
                },
                paths: |body| {
                    let EntryBody::$variant(d) = body else {
                        return Err(registry_error());
                    };
                    Ok($paths(d))
                },
                reveal: |body, field| {
                    let EntryBody::$variant(d) = body else {
                        return Err(registry_error());
                    };
                    $reveal(d, field)
                },
                subtitle: |body| {
                    let EntryBody::$variant(d) = body else {
                        return Err(registry_error());
                    };
                    Ok($subtitle(d))
                },
                digests: |body, put| {
                    let EntryBody::$variant(d) = body else {
                        return Err(registry_error());
                    };
                    $digests(d, put);
                    Ok(())
                },
            }
        }
    };
}

