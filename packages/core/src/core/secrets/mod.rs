fn registry_error() -> Error {
    Error::Internal("invalid secret kind registry".into())
}

// Kept separate from inventory collection so missing and duplicate registrations
// can be tested without poisoning the process-wide registry.
fn resolve_kind<'a>(
    kinds: &[&'a SecretKind],
    accepts: impl Fn(&SecretKind) -> bool,
) -> Result<&'a SecretKind> {
    for (i, kind) in kinds.iter().enumerate() {
        if kinds[..i]
            .iter()
            .any(|other| other.id == kind.id || other.entry_type == kind.entry_type)
        {
            return Err(registry_error());
        }
    }
    let mut matches = kinds.iter().copied().filter(|kind| accepts(kind));
    let kind = matches.next().ok_or_else(registry_error)?;
    if matches.next().is_some() {
        return Err(registry_error());
    }
    Ok(kind)
}

fn kind_for_body(body: &EntryBody) -> Result<&'static SecretKind> {
    let kinds: Vec<_> = inventory::iter::<SecretKind>.into_iter().collect();
    resolve_kind(&kinds, |kind| kind.entry_type == body.entry_type())
}

fn kind_for_payload(payload: &EntryPayload) -> Result<&'static SecretKind> {
    let kinds: Vec<_> = inventory::iter::<SecretKind>.into_iter().collect();
    resolve_kind(&kinds, |kind| (kind.accepts_payload)(payload))
}

fn invariant<T>(result: Result<T>) -> T {
    result.unwrap_or_else(|_| panic!("invalid secret kind registry"))
}

/// Registered kinds in stable identifier order. Invalid registries fail closed.
pub fn registered_kinds() -> Vec<&'static SecretKind> {
    let mut kinds: Vec<_> = inventory::iter::<SecretKind>.into_iter().collect();
    for kind in &kinds {
        invariant(resolve_kind(&kinds, |candidate| {
            candidate.entry_type == kind.entry_type
        }));
    }
    kinds.sort_by_key(|kind| kind.id);
    kinds
}

/// Type of a wire payload, resolved through the same typed adapters as merging.
pub fn payload_type(payload: &EntryPayload) -> EntryType {
    invariant(kind_for_payload(payload)).entry_type
}

/// Build the on-disk body. Absent secret values keep the stored value by path;
/// an existing body of another kind supplies no stored values.
pub fn body_from_payload(payload: &EntryPayload, stored: Option<&EntryBody>) -> Result<EntryBody> {
    (kind_for_payload(payload)?.merge)(payload, stored)
}

/// Convert a stored body to a wire payload, redacting secrets unless requested.
pub fn payload(body: &EntryBody, reveal: bool) -> EntryPayload {
    invariant(kind_for_body(body).and_then(|kind| (kind.payload)(body, reveal)))
}

/// Paths of secret fields withheld without reveal.
pub fn secret_paths(body: &EntryBody) -> Vec<String> {
    invariant(kind_for_body(body).and_then(|kind| (kind.paths)(body)))
}

/// Reveal one field, including supported plain fields and derived values.
pub fn reveal_field(body: &EntryBody, field: &str) -> Result<Zeroizing<String>> {
    (kind_for_body(body)?.reveal)(body, field)
}

/// Non-secret hint shown in lists.
pub fn subtitle(body: &EntryBody) -> Option<String> {
    let s = invariant(kind_for_body(body).and_then(|kind| (kind.subtitle)(body)));
    (!s.is_empty()).then_some(s)
}

/// Validate and normalize envelope fields of an input.
pub fn validate_input(input: &EntryInput) -> Result<()> {
    let name = input.name.trim();
    if name.is_empty() || name.len() > 256 {
        return Err(Error::invalid("entry name must be 1-256 characters"));
    }
    if name.contains('/') || name.chars().any(char::is_control) {
        return Err(Error::invalid(
            "entry name must not contain `/` or control characters",
        ));
    }
    Ok(())
}

pub fn normalize_tags(tags: &[String]) -> Vec<String> {
    let mut out: Vec<String> = vec![];
    for t in tags {
        let t = t.trim();
        if !t.is_empty() && !out.iter().any(|o| o == t) {
            out.push(t.to_owned());
        }
    }
    out
}

/// Fail when a serialized entry exceeds [`MAX_ENTRY_BYTES`].
pub fn check_size(json: &[u8]) -> Result<()> {
    if json.len() > MAX_ENTRY_BYTES {
        return Err(Error::invalid(
            "entry exceeds the 1 MiB limit; store a reference to the file instead",
        ));
    }
    Ok(())
}

fn opt(reveal: bool, v: &str) -> Option<String> {
    reveal.then(|| v.to_owned())
}

pub fn to_entry(doc: &EntryDoc, reveal: bool) -> Entry {
    Entry {
        id: doc.id.clone(),
        profile_id: doc.profile_id.clone(),
        name: doc.name.clone(),
        tags: doc.tags.clone(),
        notes: doc.notes.clone(),
        favorite: doc.favorite,
        created_at: doc.created_at.clone(),
        updated_at: doc.updated_at.clone(),
        payload: payload(&doc.body, reveal),
        redacted_fields: if reveal {
            vec![]
        } else {
            secret_paths(&doc.body)
        },
    }
}

/// Wire input reconstructing a document (fully revealed), e.g. for merges.
pub fn to_input(doc: &EntryDoc) -> EntryInput {
    EntryInput {
        profile_id: doc.profile_id.clone(),
        name: doc.name.clone(),
        tags: doc.tags.clone(),
        notes: doc.notes.clone(),
        favorite: doc.favorite,
        payload: payload(&doc.body, true),
    }
}

pub fn human_size(n: u64) -> String {
    if n < 1024 {
        format!("{n} B")
    } else if n < 1024 * 1024 {
        format!("{:.1} KB", n as f64 / 1024.0)
    } else {
        format!("{:.1} MB", n as f64 / (1024.0 * 1024.0))
    }
}

pub fn manifest_entry(doc: &EntryDoc, hash: String) -> ManifestEntry {
    ManifestEntry {
        id: doc.id.clone(),
        entry_type: doc.entry_type(),
        name: doc.name.clone(),
        tags: doc.tags.clone(),
        favorite: doc.favorite,
        subtitle: subtitle(&doc.body),
        has_totp: matches!(&doc.body, EntryBody::Login(l) if l.totp.is_some()),
        created_at: doc.created_at.clone(),
        updated_at: doc.updated_at.clone(),
        hash,
    }
}

/// Case-insensitive match over name, tags and subtitle; every whitespace
/// separated term must match.
pub fn matches(e: &ManifestEntry, query: Option<&str>, ty: Option<EntryType>) -> bool {
    if ty.is_some_and(|t| t != e.entry_type) {
        return false;
    }
    let Some(q) = query.map(str::trim).filter(|q| !q.is_empty()) else {
        return true;
    };
    let hay = format!(
        "{}\n{}\n{}",
        e.name,
        e.tags.join("\n"),
        e.subtitle.as_deref().unwrap_or("")
    )
    .to_lowercase();
    q.to_lowercase().split_whitespace().all(|t| hay.contains(t))
}

// ---------------------------------------------------------------------------
// Field diffs (history). Values never leave this function: only paths.
// ---------------------------------------------------------------------------

fn digest(v: &impl serde::Serialize) -> [u8; 32] {
    let json = Zeroizing::new(serde_json::to_vec(v).expect("serializes"));
    *blake3::hash(&json).as_bytes()
}

/// path → digest of the value.
pub fn field_digests(doc: &EntryDoc) -> BTreeMap<String, [u8; 32]> {
    let mut m = BTreeMap::new();
    m.insert("type".to_owned(), digest(&doc.entry_type()));
    m.insert("name".to_owned(), digest(&doc.name));
    m.insert("tags".to_owned(), digest(&doc.tags));
    m.insert("notes".to_owned(), digest(&doc.notes));
    m.insert("favorite".to_owned(), digest(&doc.favorite));
    m.insert("profileId".to_owned(), digest(&doc.profile_id));
    let kind = invariant(kind_for_body(&doc.body));
    invariant((kind.digests)(&doc.body, &mut |k, v| {
        m.insert(k.to_owned(), v);
    }));
    m
}

/// Paths that differ between two versions (sorted). `old = None` → all paths.
pub fn changed_fields(old: Option<&EntryDoc>, new: &EntryDoc) -> Vec<String> {
    let b = field_digests(new);
    let Some(old) = old else {
        return b
            .into_keys()
            .filter(|k| k != "type" && k != "profileId")
            .collect();
    };
    let a = field_digests(old);
    let mut out: Vec<String> = vec![];
    for (k, v) in &b {
        if a.get(k) != Some(v) {
            out.push(k.clone());
        }
    }
    for k in a.keys() {
        if !b.contains_key(k) {
            out.push(k.clone());
        }
    }
    out.sort();
    out.dedup();
    out
}

/// Field error projection for partially edited wire payloads.
pub fn validate_ui(payload: &EntryPayload, errors: &mut BTreeMap<String, String>) -> Result<()> {
    (kind_for_payload(payload)?.ui_validate)(payload, errors)
}

