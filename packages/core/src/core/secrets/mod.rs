    #[test]
    fn each_kind_preserves_history_field_paths() {
        let cases: [(EntryType, &[&str]); 8] = [
            (
                EntryType::Login,
                &[
                    "username",
                    "password",
                    "urls",
                    "custom.hidden",
                    "custom.plain",
                ],
            ),
            (EntryType::Secret, &["value"]),
            (EntryType::Env, &["vars.SECRET", "vars.PUBLIC"]),
            (EntryType::File, &["filename", "mime", "content"]),
            (EntryType::Note, &["body"]),
            (
                EntryType::SshKey,
                &["privateKey", "publicKey", "passphrase", "comment"],
            ),
            (
                EntryType::Database,
                &[
                    "engine", "host", "port", "database", "username", "password", "options",
                ],
            ),
            (
                EntryType::ApiKey,
                &["key", "secret", "endpoint", "expiresAt"],
            ),
        ];
        for (body, paths) in strategy_fixtures() {
            let expected = cases
                .iter()
                .find(|(ty, _)| *ty == body.entry_type())
                .unwrap()
                .1;
            let old = doc(body);
            let mut new = old.clone();
            let mut input = serde_json::to_value(payload(&new.body, true)).unwrap();
            for (_, pointer, _) in paths {
                // Empty values exercise both replacement and optional removal.
                *input.pointer_mut(pointer).unwrap() = serde_json::Value::String(String::new());
            }
            new.body = body_from_payload(&serde_json::from_value(input).unwrap(), None).unwrap();
            let digests = field_digests(&old);
            let mut expected: Vec<_> = expected
                .iter()
                .copied()
                .chain(["type", "name", "tags", "notes", "favorite", "profileId"])
                .collect();
            expected.sort();
            assert_eq!(
                digests.keys().map(String::as_str).collect::<Vec<_>>(),
                expected
            );
            assert!(!changed_fields(Some(&old), &new).is_empty());
            assert!(changed_fields(Some(&old), &old).is_empty());
        }
    }
